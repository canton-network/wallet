import * as path from 'path'
import type * as openrpcgen from '@open-rpc/generator'
import * as fs from 'fs'
import _ from 'lodash'
import { execSync } from 'child_process'

// eslint-disable-next-line @typescript-eslint/no-explicit-any
const onlyHandleTS = ({ language }: any) => {
    if (language !== 'typescript') {
        throw new Error(
            'Cannot handle any other language other than TS for server generator'
        )
    }
}

const methodMappingTemplate =
    _.template(`// Code generated by rpc-generator DO NOT EDIT!!

<% openrpcDocument.methods.forEach(({ name }) => { %> import type { <%= _.upperFirst(name) %> } from "./typings.js";
<% }); %>

export type Methods = {
    <% openrpcDocument.methods.forEach(({ name }) => { %>  <%= name %>: <%= _.upperFirst(name) %>,
    <% }); %>
};

function buildController(methods: Methods) {
     return {
        <% openrpcDocument.methods.forEach(({ name }) => { %>  <%= name %>: methods.<%= name %>,
        <% }); %>};
}

export default buildController;
`)

const generatedTypingsTemplate = _.template(
    `// Code generated by rpc-generator DO NOT EDIT!!
/* eslint-disable @typescript-eslint/no-explicit-any */
/* eslint-disable @typescript-eslint/no-unused-vars */

<%= methodTypings.toString("typescript").replace(/export type AnyOf[A-Za-z0-9]+ =(?:[\\r\\n]|.)*?;/gm, "") %>
`
)

export const hooks: openrpcgen.components.IHooks = {
    afterCompileTemplate: [
        async (dest, _, component): Promise<void> => {
            onlyHandleTS(component)
            if (fs.existsSync(path.join(dest, 'src'))) {
                fs.rmSync(path.join(dest, 'src'), {
                    recursive: true,
                    force: true,
                })
            }
            execSync(`pnpm eslint --fix ${dest}`)
            execSync(
                `pnpm prettier --write --no-error-on-unmatched-pattern ${dest}/**/*`
            )
        },
    ],
    templateFiles: {
        typescript: [
            {
                path: 'index.ts',
                template: methodMappingTemplate,
            },
            {
                path: 'typings.ts',
                template: generatedTypingsTemplate,
            },
        ],
    },
}

export default {
    hooks,
    staticPath: () =>
        path.join(import.meta.dirname, '../../templates/controller/'),
    openRPCPath: undefined,
}
